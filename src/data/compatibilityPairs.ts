/**
 * Returns a candidate pair by slug or undefined
 */
export function getCandidatePairBySlug(slug: string): CompatibilityPairCandidate | undefined {
  return CANDIDATE_COMPATIBILITY_PAIRS.find(p => p.pairSlug === slug);
}

/**
 * Finds all candidate pairs associated with a specific sign
 */
export function getCandidatePairsForSign(signId: WesternZodiacSign): readonly CompatibilityPairCandidate[] {
  return CANDIDATE_COMPATIBILITY_PAIRS.filter(p => p.sign1 === signId || p.sign2 === signId);
}
